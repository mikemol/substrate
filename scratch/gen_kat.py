"""gen_kat.py — generate-and-measure engine for the AES-128 full-KAT proof tricks.

The extruder gives the <-min interleave STRUCTURE; THIS gives the cheap
ELABORATION by baking in our memory tricks (which the extruder can't emit):
  - abstract-Assemble    : keeps round/nextRoundKey NEUTRAL (no deep WHNF)
  - opaque fold-trace     : discharges the fold-congruences ONCE, generically
  - lazy flat chain       : a cons-list of shallow steps, not a deep trans-nest

Emit a trick-laden interleaved AES-128 full-encrypt KAT for a chosen emission
VARIANT, compile it under membudget, report the peak maxRSS. Trick-exploration
is now a mechanized sweep instead of hand-written FullIL + hand membudget runs.

Reproduces the hand-measured points:  eager -> 225 MB,  lazy -> 197 MB (VALIDATED).

Variants:
  eager  — hand-built n-deep trans-nest over pairs  (FullIL v1)
  lazy   — data ILChain + opaque il-chain-sound      (FullIL v2)

Usage:
  python3 scratch/gen_kat.py --variant lazy
  python3 scratch/gen_kat.py --sweep
  python3 scratch/gen_kat.py --variant lazy --emit-only
"""
import argparse, os, subprocess

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AGDA = os.path.join(REPO, "agda")
MEMBUDGET = os.path.join(REPO, "scripts", "membudget")
MODNAME = "Substrate.Algebra.F2.AES.KAT.FullKATGen"
RELPATH = "Substrate/Algebra/F2/AES/KAT/FullKATGen.agda"
LEDGER = os.path.join(AGDA, "Substrate", "Algebra", "F2", "AES", "KAT", ".agda-times.tsv")
VARIANTS = ("eager", "lazy")


def kvar(i):                       # abstract key var: k0 = mk, else k{i}
    return "mk" if i == 0 else f"k{i}"


def fold_arg(lo, hi):              # "[]" or "(rc{lo} ∷ .. ∷ rc{hi} ∷ [])"
    xs = [f"rc{j}" for j in range(lo, hi + 1)]
    return "[]" if not xs else "(" + " ∷ ".join(xs + ["[]"]) + ")"


def build_lazy_chain(n):           # cons st1 (cons st2 (... (cons st{n} nil)))
    inner = "nil"
    for i in range(n, 0, -1):
        inner = f"cons st{i} nil" if i == n else f"cons st{i} ({inner})"
    return inner


def build_eager_nest(n):           # trans (cong (fold il-step T1) st1) (... (cong (fold il-step []) st{n}))
    inner = f"cong (fold il-step {fold_arg(n + 1, n)}) st{n}"
    for i in range(n - 1, 0, -1):
        inner = f"trans (cong (fold il-step {fold_arg(i + 1, n)}) st{i}) ({inner})"
    return inner


def emit(n, variant):
    lazy = variant == "lazy"
    L = [
        "{-# OPTIONS --safe --without-K #-}",
        "------------------------------------------------------------------------",
        f"-- {MODNAME}   (GENERATED by scratch/gen_kat.py, variant = {variant})",
        "--",
        "-- Trick-laden interleaved AES-128 full-KAT. The extruder gives the <-min",
        "-- interleave STRUCTURE; the abstract-Assemble / opaque fold-trace / lazy",
        "-- chain tricks give the cheap ELABORATION. DO NOT EDIT -- regenerate:",
        f"--   python3 scratch/gen_kat.py --variant {variant}",
        "------------------------------------------------------------------------",
        "",
        f"module {MODNAME} where",
        "",
        # ⚑ `Foundation.Nat` WAS DISSOLVED into 62 leaves; `ℕ` lives in
        # `Foundation.Nat.Nat`. The generated module was the LAST dangling
        # importer of that parent, and editing the OUTPUT is futile — its own
        # header says DO NOT EDIT and the next `--variant lazy` run would restore
        # the break. A generated file's import list is the GENERATOR's source.
        "open import Substrate.Foundation.Nat.Nat",
        # ⚑ `Foundation.Eq` was decomposed too: it keeps `_≡_`/`refl` and the
        # combinators moved to their own leaves. The `using` clause named three
        # names it no longer exports, which is only a WARNING — so the generated
        # module bound nothing and failed at the first use site (:56 `trans`).
        "open import Substrate.Foundation.Eq",
        "open import Substrate.Foundation.Eq.Trans",
        "open import Substrate.Foundation.Eq.Cong",
        "open import Substrate.Foundation.Eq.Cong2",
        "open import Substrate.Foundation.Vec using (Vec; _∷_; [])",
        "open import Substrate.Foundation.Product using (_×_; _,_; proj₁; proj₂)",
        "open import Substrate.Algebra.F2.AES.Round using (Byte; State; round; final-round; addKey)",
        "open import Substrate.Algebra.F2.AES.Cipher using (fold)",
        "open import Substrate.Algebra.F2.AES.KeySchedule",
        "  using (nextRoundKey; " + "; ".join(f"rc{j}" for j in range(1, n + 2)) + ")",
        "open import Substrate.Algebra.F2.AES.KAT using (to-state; key-C1)",
        "open import Substrate.Algebra.F2.AES.KAT.Trace",
        "open import Substrate.Algebra.F2.AES.KAT.Pre using (pre)",
        "open import Substrate.Algebra.F2.AES.KAT.KeyPins",
    ]
    for i in range(1, n + 1):
        L.append(f"open import Substrate.Algebra.F2.AES.KAT.Round{i} using (r{i})")
    L += [
        "open import Substrate.Algebra.F2.AES.KAT.RoundFin using (fin)",
        "",
        "il-step : Byte → State × State → State × State",
        "il-step rc (k , s) = nextRoundKey rc k , round (nextRoundKey rc k) s",
        "",
        "mids : _",
        "mids = " + " ∷ ".join([f"rc{j}" for j in range(1, n + 1)] + ["[]"]),
        "",
        "il-run : State → State → State",
        "il-run key pt =",
        f"  final-round (nextRoundKey rc{n + 1} (proj₁ (fold il-step mids (key , addKey key pt))))",
        "              (proj₂ (fold il-step mids (key , addKey key pt)))",
        "",
    ]
    if lazy:
        L += [
            "data ILChain : ∀ {m} → Vec Byte m → State × State → State × State → Set where",
            "  nil  : ∀ {p} → ILChain [] p p",
            "  cons : ∀ {m rc} {rcs : Vec Byte m} {p p' q}",
            "       → il-step rc p ≡ p' → ILChain rcs p' q → ILChain (rc ∷ rcs) p q",
            "",
            "opaque",
            "  il-chain-sound : ∀ {m} {rcs : Vec Byte m} {p q}",
            "                 → ILChain rcs p q → fold il-step rcs p ≡ q",
            "  il-chain-sound nil                     = refl",
            "  il-chain-sound (cons {rcs = rcs} st r) = trans (cong (fold il-step rcs) st) (il-chain-sound r)",
            "",
        ]
    # ── the abstract Assemble module (keeps ops neutral) ──
    states = "mk spt sct " + " ".join(f"s{i}" for i in range(0, n + 1)) \
        + " " + " ".join(f"k{i}" for i in range(1, n + 2)) + " : State"
    L += ["module Assemble", f"  ({states})"]
    for i in range(1, n + 2):                 # key pins kp1..kp{n+1}
        L.append(f"  (kp{i} : nextRoundKey rc{i} {kvar(i - 1)} ≡ k{i})")
    L.append("  (p  : addKey mk spt ≡ s0)")
    for i in range(1, n + 1):                 # round pins e1..e{n}
        L.append(f"  (e{i} : round k{i} s{i - 1} ≡ s{i})")
    L += [
        f"  (f  : final-round k{n + 1} s{n} ≡ sct)",
        "  where",
        "",
    ]
    for i in range(1, n + 1):                 # the shallow per-rung steps
        L.append(f"  st{i} : il-step rc{i} ({kvar(i - 1)} , s{i - 1}) ≡ (k{i} , s{i})")
        L.append(f"  st{i} = cong₂ _,_ kp{i} (trans (cong (λ k → round k s{i - 1}) kp{i}) e{i})")
    L.append("")
    if lazy:
        L += [
            f"  chain : ILChain mids (mk , s0) (k{n} , s{n})",
            "  chain = " + build_lazy_chain(n),
            "",
            f"  p9-eq : fold il-step mids (mk , addKey mk spt) ≡ (k{n} , s{n})",
            "  p9-eq = trans (cong (λ x → fold il-step mids (mk , x)) p) (il-chain-sound chain)",
        ]
    else:
        L += [
            f"  il-mid-eq : fold il-step mids (mk , s0) ≡ (k{n} , s{n})",
            "  il-mid-eq = " + build_eager_nest(n),
            "",
            f"  p9-eq : fold il-step mids (mk , addKey mk spt) ≡ (k{n} , s{n})",
            "  p9-eq = trans (cong (λ x → fold il-step mids (mk , x)) p) il-mid-eq",
        ]
    L += [
        "",
        f"  kat : il-run mk spt ≡ sct",
        "  kat = trans (cong₂ final-round",
        f"                (trans (cong (λ pr → nextRoundKey rc{n + 1} (proj₁ pr)) p9-eq) kp{n + 1})",
        "                (cong proj₂ p9-eq))",
        "              f",
        "",
        "open Assemble (to-state key-C1) Spt Sct "
        + " ".join(f"S{i}" for i in range(0, n + 1)),
    ]
    # concrete keys: k1..k{n} = M0..M{n-1}, k{n+1} = K10
    concrete_k = " ".join(f"M{i}" for i in range(0, n)) + " K10"
    concrete_kp = " ".join(f"KP{i}" for i in range(1, n + 2))
    concrete_e = " ".join(f"r{i}" for i in range(1, n + 1))
    L += [
        f"              {concrete_k}",
        f"              {concrete_kp}",
        f"              pre {concrete_e} fin",
        "  public renaming (kat to encrypt-il-kat-C1)",
    ]
    return "\n".join(L) + "\n"


def write_module(src):
    path = os.path.join(AGDA, RELPATH)
    with open(path, "w") as fh:
        fh.write(src)
    return path


def measure(mb):
    # fresh typecheck (source changed → agda re-checks); read the LAST ledger row.
    r = subprocess.run(
        [MEMBUDGET, "run", str(mb), "genkat", "--",
         "agda", "--safe", "--without-K", "-i.", RELPATH],
        cwd=AGDA, capture_output=True, text=True)
    peak = secs = None
    try:
        with open(LEDGER) as fh:
            for line in fh:
                if line.startswith("FullKATGen.agda\t"):
                    _, secs, peak = line.rstrip("\n").split("\t")[:3]
    except FileNotFoundError:
        pass
    return r.returncode, peak, secs, (r.stdout + r.stderr)


def run_one(n, variant, mb, emit_only):
    src = emit(n, variant)
    write_module(src)
    if emit_only:
        print(f"[{variant}] emitted {RELPATH} ({len(src.splitlines())} lines)")
        return None
    rc, peak, secs, out = measure(mb)
    ok = "OK " if rc == 0 else f"FAIL({rc})"
    print(f"[{variant:5}] {ok} peak={peak} MB  secs={secs}")
    if rc != 0:
        print("\n".join(out.splitlines()[-15:]))
    return (variant, rc, peak, secs)


# ══════════════════════════════════════════════════════════════════════════
# ⟡il-shard: SHARDED generate-and-measure. Splits the n-round fold into K
# sub-chain modules (each an opaque `fold round [g keys] p ≡ q` midpoint) +
# a sealed key-schedule module + a thin aggregator that stitches the sealed
# midpoints via `fold-++` — the sequential form of KAT.Full's shipped shards.
# Emits DISTINCT probe modules (FullKATGenS*) so it never clobbers the shipped
# Full/FullKeySched/FullFcShard*. K is sweepable → find the min per-module peak.
# ══════════════════════════════════════════════════════════════════════════
NS = "Substrate.Algebra.F2.AES.KAT"


def _kname(i):                       # concrete round key kᵢ (1..9 → M0..M8, 10 → K10)
    return "K10" if i == 10 else f"M{i - 1}"


def _grps(n, K):                     # split rounds 1..n into K contiguous groups
    g, out, lo = n // K, [], 1
    for i in range(K):
        hi = n if i == K - 1 else lo + g - 1
        out.append((lo, hi)); lo = hi + 1
    return out


def _sharded_modules(n, K):
    grps = _grps(n, K)
    mods = {}   # basename -> src

    # ── Core: fold-++ ──
    mods["FullKATGenSCore"] = f"""{{-# OPTIONS --safe --without-K #-}}
module {NS}.FullKATGenSCore where
open import Substrate.Foundation.Eq using (_≡_; refl)
open import Substrate.Foundation.Vec using (Vec; _∷_; []; _++_)
open import Substrate.Algebra.F2.AES.Cipher using (fold)
fold-++ : ∀ {{A S : Set}} {{m n}} (f : A → S → S) (xs : Vec A m) (ys : Vec A n) (s : S)
        → fold f (xs ++ ys) s ≡ fold f ys (fold f xs s)
fold-++ f []       ys s = refl
fold-++ f (x ∷ xs) ys s = fold-++ f xs ys (f x s)
"""

    # ── KeySched: rkmid mk ≡ ms / rk10 mk ≡ k10, sealed (fixed for n rounds) ──
    kparams = " ".join(f"k{i}" for i in range(1, n + 1)) + " k10"
    kpdecls = "\n  ".join(
        f"(kp{i} : nextRoundKey rc{i} {'mk' if i == 1 else f'k{i-1}'} ≡ k{i})"
        for i in range(1, n + 2))
    cks = "\n  ".join(
        [f"ck1 = kp1"] +
        [f"ck{i} = trans (cong (nextRoundKey rc{i}) ck{i-1}) kp{i}" for i in range(2, n + 2)])
    ms_vec = " ∷ ".join(f"k{i}" for i in range(1, n + 1)) + " ∷ []"
    rkmid_body = "refl"
    for i in range(n, 0, -1):
        rkmid_body = f"cong₂ _∷_ ck{i} ({rkmid_body})"
    open_ks = " ".join(f"{_kname(i)}" for i in range(1, n + 1)) + " K10 " + \
              " ".join(f"KP{i}" for i in range(1, n + 2))
    ms_conc = " ∷ ".join(_kname(i) for i in range(1, n + 1)) + " ∷ []"
    ks_trace = "; ".join(sorted(set(_kname(i) for i in range(1, n + 1)) | {"K10"}))
    ks_rcs = "; ".join(f"rc{i}" for i in range(1, n + 2))
    mods["FullKATGenSKS"] = f"""{{-# OPTIONS --safe --without-K #-}}
module {NS}.FullKATGenSKS where
open import Substrate.Foundation.Eq using (_≡_; refl; trans; cong; cong₂)
open import Substrate.Foundation.Vec using (Vec; _∷_; [])
open import Substrate.Algebra.F2.AES.Round using (State)
open import Substrate.Algebra.F2.AES.KeySchedule
  using (nextRoundKey; rkmid; rk10; {ks_rcs})
open import {NS} using (to-state; key-C1)
open import {NS}.Trace using ({ks_trace})
open import {NS}.KeyPins
module AssembleK
  ({'mk ' + kparams} : State)
  {kpdecls}
  where
  {cks}
  ms : Vec State {n}
  ms = {ms_vec}
  rkmid-eq : rkmid mk ≡ ms
  rkmid-eq = {rkmid_body}
  rk10-eq : rk10 mk ≡ k10
  rk10-eq = ck{n + 1}
open AssembleK (to-state key-C1) {open_ks} using (rkmid-eq; rk10-eq)
opaque
  rkmid-eq-C : rkmid (to-state key-C1) ≡ ({ms_conc})
  rkmid-eq-C = rkmid-eq
  rk10-eq-C : rk10 (to-state key-C1) ≡ K10
  rk10-eq-C = rk10-eq
"""

    # ── K round-fold shards ──
    for idx, (lo, hi) in enumerate(grps):
        sp = " ".join(f"s{i}" for i in range(lo - 1, hi + 1))
        kp = " ".join(f"k{i}" for i in range(lo, hi + 1))
        edecls = "\n  ".join(f"(e{j} : round k{j} s{j-1} ≡ s{j})" for j in range(lo, hi + 1))
        kvec = " ∷ ".join(f"k{i}" for i in range(lo, hi + 1)) + " ∷ []"
        body = f"cong (fold round []) e{hi}"
        for j in range(hi - 1, lo - 1, -1):
            rem = "(" + " ∷ ".join([f"k{x}" for x in range(j + 1, hi + 1)] + ["[]"]) + ")"
            body = f"trans (cong (fold round {rem}) e{j})\n        ({body})"
        rimp = "\n".join(f"open import {NS}.Round{j} using (r{j})" for j in range(lo, hi + 1))
        tnames = sorted({f"S{i}" for i in range(lo - 1, hi + 1)} | {_kname(i) for i in range(lo, hi + 1)})
        oc = " ".join(f"S{i}" for i in range(lo - 1, hi + 1)) + " " + \
             " ".join(_kname(i) for i in range(lo, hi + 1)) + " " + \
             " ".join(f"r{j}" for j in range(lo, hi + 1))
        ckvec = " ∷ ".join(_kname(i) for i in range(lo, hi + 1)) + " ∷ []"
        mods[f"FullKATGenSR{idx}"] = f"""{{-# OPTIONS --safe --without-K #-}}
module {NS}.FullKATGenSR{idx} where
open import Substrate.Foundation.Eq using (_≡_; trans; cong)
open import Substrate.Foundation.Vec using (_∷_; [])
open import Substrate.Algebra.F2.AES.Round using (State; round)
open import Substrate.Algebra.F2.AES.Cipher using (fold)
open import {NS}.Trace using ({'; '.join(tnames)})
{rimp}
module AssembleR{idx}
  ({sp} {kp} : State)
  {edecls}
  where
  fc{idx} : fold round ({kvec}) s{lo-1} ≡ s{hi}
  fc{idx} = {body}
open AssembleR{idx} {oc} using (fc{idx})
opaque
  fc{idx}-C : fold round ({ckvec}) S{lo-1} ≡ S{hi}
  fc{idx}-C = fc{idx}
"""

    # ── aggregator: compose the K midpoints via fold-++ + assemble the KAT ──
    msg_defs = "\n".join(
        f"msg{i} : _\nmsg{i} = " + " ∷ ".join(_kname(x) for x in range(lo, hi + 1)) + " ∷ []"
        for i, (lo, hi) in enumerate(grps))
    ms_all = " ∷ ".join(_kname(i) for i in range(1, n + 1)) + " ∷ []"
    parts = []
    for i in range(K - 1):
        tail = " ++ ".join(f"msg{j}" for j in range(i + 1, K))
        start = "S0" if i == 0 else f"S{grps[i-1][1]}"
        parts.append(f"fold-++ round msg{i} ({tail}) {start}")
        parts.append(f"cong (fold round ({tail})) fc{i}-C")
    parts.append(f"fc{K-1}-C")
    comp = parts[-1]
    for p in reversed(parts[:-1]):
        comp = f"trans ({p})\n     ({comp})"
    fc_imports = "\n".join(f"open import {NS}.FullKATGenSR{i} using (fc{i}-C)" for i in range(K))
    tnames_agg = sorted({"Spt", "Sct", "S0", "S9", "K10"} |
                        {f"S{grps[i-1][1]}" for i in range(1, K)} |
                        {_kname(i) for i in range(1, n + 1)})
    mods["FullKATGen"] = f"""{{-# OPTIONS --safe --without-K #-}}
-- GENERATED by scratch/gen_kat.py --variant sharded --shards {K}. PROBE (not the shipped Full).
module {NS}.FullKATGen where
open import Substrate.Foundation.Eq using (_≡_; trans; cong; cong₂)
open import Substrate.Foundation.Vec using (Vec; _∷_; []; _++_)
open import Substrate.Algebra.F2.AES.Round using (State; round; final-round; addKey)
open import Substrate.Algebra.F2.AES.Cipher using (fold)
open import Substrate.Algebra.F2.AES.KeySchedule using (encrypt-key)
open import {NS} using (to-state; key-C1)
open import {NS}.Trace using ({'; '.join(tnames_agg)})
open import {NS}.Pre using (pre)
open import {NS}.RoundFin using (fin)
open import {NS}.FullKATGenSCore using (fold-++)
open import {NS}.FullKATGenSKS using (rkmid-eq-C; rk10-eq-C)
{fc_imports}

mk : State
mk = to-state key-C1
{msg_defs}
ms : Vec State {n}
ms = {ms_all}

fc : fold round ms S0 ≡ S9
fc = {comp}

encrypt-kat-C1 : encrypt-key mk Spt ≡ Sct
encrypt-kat-C1 =
  trans (cong₂ (λ k m → final-round k (fold round m (addKey mk Spt))) rk10-eq-C rkmid-eq-C)
  (trans (cong (λ x → final-round K10 (fold round ms x)) pre)
  (trans (cong (final-round K10) fc) fin))
"""
    return mods


def run_sharded(n, K, mb, emit_only):
    mods = _sharded_modules(n, K)
    paths = {}
    for base, src in mods.items():
        p = os.path.join(AGDA, "Substrate", "Algebra", "F2", "AES", "KAT", base + ".agda")
        with open(p, "w") as fh:
            fh.write(src)
        paths[base] = p
    try:
        if emit_only:
            print(f"[sharded K={K}] emitted {len(mods)} modules: {', '.join(mods)}")
            return
        # Compile EACH module in its own process (as `make -f Flat.mk` does) so the
        # per-module peak is faithful; the MAX is the binding module for the cap.
        order = (["FullKATGenSCore", "FullKATGenSKS"]
                 + [f"FullKATGenSR{i}" for i in range(K)] + ["FullKATGen"])
        peaks, failed = {}, None
        for base in order:
            rel = f"Substrate/Algebra/F2/AES/KAT/{base}.agda"
            r = subprocess.run(
                [MEMBUDGET, "run", str(mb), "genkat-shard", "--",
                 "agda", "--safe", "--without-K", "-i.", rel],
                cwd=AGDA, capture_output=True, text=True)
            try:
                with open(LEDGER) as fh:
                    for line in fh:
                        if line.startswith(base + ".agda\t"):
                            peaks[base] = line.rstrip("\n").split("\t")[2]
            except FileNotFoundError:
                pass
            if r.returncode != 0:
                failed = (base, (r.stdout + r.stderr)); break
        ok = "OK " if failed is None else f"FAIL({failed[0]})"
        binding = max((int(v) for v in peaks.values()), default="?")
        print(f"[sharded K={K}] {ok}  MAX per-module peak = {binding} MB  (binding module)")
        for b in order:
            if b in peaks:
                print(f"    {b:22} {peaks[b]} MB")
        if failed is not None:
            print("\n".join(failed[1].splitlines()[-15:]))
    finally:
        for base, p in paths.items():
            for f in (p, os.path.join(AGDA, "_build", "2.8.0", "agda",
                                      "Substrate", "Algebra", "F2", "AES", "KAT", base + ".agdai")):
                try: os.remove(f)
                except FileNotFoundError: pass


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--variant", choices=VARIANTS + ("sharded",))
    ap.add_argument("--shards", type=int, default=3)
    ap.add_argument("--sweep", action="store_true")
    ap.add_argument("--emit-only", action="store_true")
    ap.add_argument("-n", type=int, default=9)
    ap.add_argument("--mb", type=int, default=768)
    a = ap.parse_args()
    if a.variant == "sharded":
        run_sharded(a.n, a.shards, a.mb, a.emit_only)
    elif a.sweep:
        rows = [run_one(a.n, v, a.mb, a.emit_only) for v in VARIANTS]
        print("\n=== sweep (n=%d) ===" % a.n)
        for row in rows:
            if row:
                print("  %-6s exit=%s peak=%s MB secs=%s" % row)
    else:
        run_one(a.n, a.variant or "lazy", a.mb, a.emit_only)


if __name__ == "__main__":
    main()
