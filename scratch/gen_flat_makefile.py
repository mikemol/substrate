"""PROTOTYPE ⟡make-import-dag: a SINGLE flat makefile whose per-module targets carry their
DIRECT-import prerequisites from catalog.db module_edges — so `make -j` builds in true import-DAG
topological order (deps first, independents concurrent, NO on-the-fly, NO racing).

Design: each module is a PHONY target named `m/<Module>` depending on `m/<import>` for each direct
import, recipe = `agda … <src>`. Preserves the current model (agda owns _build + content-hash
caching; make always dispatches) and ONLY fixes ORDERING. No coupling to _build/agda-version paths.

Run from the repo root: python3 scratch/gen_flat_makefile.py > agda/Flat.mk
Diagnostics (coverage, cycles) go to stderr.
"""
import sqlite3, os, glob, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AGDA = os.path.join(REPO, "agda")
CATALOG = os.path.join(REPO, "catalog", "catalog.db")
SHIM = os.path.join(REPO, "scripts", "agda-shim")

def mod_of(relpath):  # Substrate/Foundation/Fin.agda -> Substrate.Foundation.Fin
    return relpath[:-5].replace(os.sep, ".")
def src_of(mod):      # Substrate.Foundation.Fin -> Substrate/Foundation/Fin.agda  (only '.'→'/', '-' stays)
    return mod.replace(".", "/") + ".agda"

# 1. disk modules = the source of truth for WHAT to build (Substrate/**, minus All = OOM by design)
disk = set()
for f in glob.glob(os.path.join(AGDA, "Substrate", "**", "*.agda"), recursive=True):
    disk.add(mod_of(os.path.relpath(f, AGDA)))
disk.discard("Substrate.All")

# 2. direct-import edges from catalog.db, restricted to disk modules
con = sqlite3.connect(f"file:{CATALOG}?mode=ro", uri=True)
edges = con.execute(
    "SELECT src,dst FROM module_edges WHERE src LIKE 'Substrate.%' AND dst LIKE 'Substrate.%'").fetchall()
deps = {m: set() for m in disk}
cat_nodes = set()
for s, d in edges:
    cat_nodes.add(s); cat_nodes.add(d)
    if s in disk and d in disk and d != s:
        deps[s].add(d)

# The def-less re-export aggregators (on disk, no catalog node) get a FAKE "build after the rest"
# dependency: they depend on the sentinel `rest` (= every catalog-covered module), so agda self-heals
# their `open import … public` children AFTER those children are built (ordered, not racing). This clean
# ordered build feeds a fresh catalog.db; proper deps follow. cat_nodes carry no edge TO these, so acyclic.
uncovered = disk - cat_nodes                 # the 118 re-export aggregators
covered   = disk - uncovered
REST = "rest"                                 # sentinel target = all covered modules built

# 3. coverage diagnostics (stderr)
missing_in_cat = sorted(disk - cat_nodes)   # on disk but no catalog node → built with NO ordered deps (fallback to agda on-the-fly)
stale_in_cat  = sorted(cat_nodes - disk - {"Substrate.All"})  # in catalog but not on disk (renamed/deleted; ignored)
print(f"[gen_flat] disk modules: {len(disk)}", file=sys.stderr)
print(f"[gen_flat] catalog nodes: {len(cat_nodes)}  edges: {len(edges)}", file=sys.stderr)
print(f"[gen_flat] on-disk-not-in-catalog (no DAG deps → agda self-heals these): {len(missing_in_cat)}", file=sys.stderr)
for m in missing_in_cat[:15]: print(f"           - {m}", file=sys.stderr)
print(f"[gen_flat] in-catalog-not-on-disk (ignored): {len(stale_in_cat)}", file=sys.stderr)

# 4. cycle check (agda modules are acyclic; a cycle would hang make) — Kahn
indeg = {m: 0 for m in disk}
for m in disk:
    for d in deps[m]:
        indeg[m] += 1  # m depends on d; count m's in-edges (deps)
# topo via Kahn on the dep graph (edge m -> its deps means deps must come first)
from collections import deque
radj = {m: set() for m in disk}       # reverse: d -> {modules that depend on d}
for m in disk:
    for d in deps[m]:
        radj[d].add(m)
ind = {m: len(deps[m]) for m in disk}
q = deque(m for m in disk if ind[m] == 0)
seen = 0
while q:
    x = q.popleft(); seen += 1
    for m in radj[x]:
        ind[m] -= 1
        if ind[m] == 0: q.append(m)
if seen != len(disk):
    cyc = [m for m in disk if ind[m] > 0]
    print(f"[gen_flat] ⚠ CYCLE among {len(cyc)} modules (make would hang): {cyc[:8]}", file=sys.stderr)
    sys.exit(2)
print(f"[gen_flat] acyclic ✓ ({seen} modules topo-sortable)", file=sys.stderr)

# 5. emit the flat makefile (stdout)
def tgt(m): return "m/" + m
out = []
w = out.append
w("# GENERATED by scratch/gen_flat_makefile.py — ⟡make-import-dag PROTOTYPE. Do not edit.")
w("# Single flat makefile: per-module PHONY target + direct-import prereqs from catalog.db → make -j builds in import-DAG order.")
w("MEM_CAP    ?= 256m")
w("AGDA       ?= agda")
w("AGDA_FLAGS ?= --safe --without-K")
w(f"SHIM_DIR   := {SHIM}")
w("export PATH := $(SHIM_DIR):$(PATH)")   # route bare `agda` through the membudget shim
w("AGDA_ROOT  := .")
w("")
w(".PHONY: all check-sync " + REST + " " + " ".join(tgt(m) for m in sorted(disk)))
w("")
w("all: check-sync " + " ".join(tgt(m) for m in sorted(disk)))
w("")
w("# sentinel: every catalog-covered module built (the def-less re-export aggregators depend on this)")
w(REST + ": " + " ".join(tgt(m) for m in sorted(covered)))
w("")
w("check-sync:")
w("\t@disk=`cd $(AGDA_ROOT) 2>/dev/null; find Substrate -name '*.agda' | sed 's#/#.#g; s#\\.agda$$##' | grep -v '^Substrate.All$$' | sort`; \\")
w(f"\t gen=`printf '%s\\n' {' '.join(sorted(disk))} | tr ' ' '\\n' | sort`; \\")
w("\t if [ \"$$disk\" != \"$$gen\" ]; then echo 'ERROR: disk .agda set differs from generated targets — regen Flat.mk'; exit 1; fi")
w("")
for m in sorted(disk):
    pre = (REST if m in uncovered else " ".join(tgt(d) for d in sorted(deps[m])))
    w(f"{tgt(m)}: {pre}".rstrip())
    w(f"\t@$(AGDA) $(AGDA_FLAGS) +RTS -M$(MEM_CAP) -RTS -i $(AGDA_ROOT) $(AGDA_ROOT)/{src_of(m)}")
    w("")
sys.stdout.write("\n".join(out) + "\n")
print(f"[gen_flat] emitted {len(disk)} module rules", file=sys.stderr)
