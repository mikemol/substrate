"""The build's settings — ONE owner for the figures both generated makefiles embed.

⚑⚑⚑ DRAINED FROM `scripts/gen_build_makefiles.py` (⟡promote-path A, step 3). That file carries
292 findings and the per-file gate refuses every edit, so its constants and small readers move
here, and the final shim will re-export them. Until the shim lands BOTH files hold these values,
which is only acceptable because `build_settings_selftest` compares every one against the origin
and fails the moment they differ. That differential retires with the origin.

⚑⚑ `MEM_CAP` IS A GATE AND `AGDA_JOBS` IS A WIDTH, NOT FIGURES TO QUOTE (CLAUDE.md). Nothing else
in the tree should restate either; ask this module (or, until the shim, the origin).

⚑ `jobs()` RAISES A TYPED ERROR, NOT `SystemExit`. The origin exited from inside a library
function, so no caller could ask for the width without being killed by a bad override. The CLI
layer decides the exit code. ⚑ And the CLI must print ONLY the number for `--jobs`: pre-commit
reads it inside `$(… 2>/dev/null)` with a bare `-j` fallback, so extra text or a crash silently
unthrottles the build.
"""

from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AGDA_DIR = ROOT / "agda"
SRC = AGDA_DIR / "Substrate"
#: ⟡cap-128-forcing: the per-file GHC heap cap, enforced at the agda parameter. A GATE.
MEM_CAP = "128m"
#: ⟡agda-jobs: the `make -j` width, a string as the origin holds it; `AGDA_JOBS` env overrides.
AGDA_JOBS = "20"
MARKER = "# GENERATED by scripts/gen_build_makefiles.py — do not edit by hand."
SHIM_DIR = ROOT / "scripts" / "agda-shim"
MEMBUDGET = ROOT / "scripts" / "membudget"
#: The interface version assumed when neither the build tree nor `agda` can answer.
FALLBACK_VER = "2.8.0"


class JobsError(ValueError):
    """`AGDA_JOBS` is set to something that is not a positive integer."""


def jobs() -> int:
    """Return the `make -j` width — `AGDA_JOBS` from the environment, else the constant.

    ⚑ A malformed override REFUSES rather than falling back: `AGDA_JOBS=abc` quietly becoming 20
    would be a knob that reads as set and is not.
    """
    raw = os.environ.get("AGDA_JOBS", AGDA_JOBS).strip()
    if not raw.isdigit():
        msg = f"AGDA_JOBS={raw!r} is not an integer (the make -j width); unset it or give one"
        raise JobsError(msg)
    n = int(raw)
    if n < 1:
        msg = f"AGDA_JOBS={n} must be >= 1"
        raise JobsError(msg)
    return n


def jobs_flag() -> list[str]:
    """Return `["-j", "<n>"]` — the fragment every constructed `make` call splices in."""
    return ["-j", str(jobs())]


def build_ver() -> str:
    """Return the agda interface version: on-disk `_build/<ver>/agda`, else `agda`, else 2.8.0."""
    found = sorted(p for p in AGDA_DIR.glob("_build/*/agda") if p.is_dir())
    if found:
        return found[-1].parent.name
    agda = shutil.which("agda")
    if agda is None:
        return FALLBACK_VER
    try:
        out = subprocess.run(
            [agda, "--numeric-version"], capture_output=True, text=True, check=True, timeout=30
        )
    except (OSError, subprocess.SubprocessError):
        return FALLBACK_VER
    return out.stdout.strip() or FALLBACK_VER


def shim_block() -> list[str]:
    """Return the makefile lines that put the membudget agda-shim on PATH and name MEMBUDGET."""
    return [
        (
            "# membudget agda-shim → make is the controlled+instrumented build path "
            "(RAM-budgeted + proof-cost"
        ),
        (
            "# profiled). Idempotent (findstring); exported to recipes + sub-makes. "
            "MEMBUDGET_NOPROFILE=1 to skip"
        ),
        "# profiling; `make AGDA=…` to pin a different agda.",
        f"SHIM_DIR := {SHIM_DIR}",
        "ifeq (,$(findstring $(SHIM_DIR),$(PATH)))",
        "export PATH := $(SHIM_DIR):$(PATH)",
        "endif",
        f"MEMBUDGET := {MEMBUDGET}",
        "export MEMBUDGET",
        "",
    ]
