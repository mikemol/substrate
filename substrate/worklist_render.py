"""Render the worklist as rows and as the ledger's generated markdown block.

⚑⚑⚑ RENDERING IS SEPARATE FROM DECIDING, AND THE ORIGIN FUSED THEM. `scripts/worklist.py` computed
a verdict and formatted it in the same comprehension, three times, with the tally recomputed by
re-walking the roster at each site — so a change to the glyph set or the tally had three homes and
`rows()` was iterated four times per run. Here the verdict comes from `worklist_status` and this
module only says how it LOOKS.

⚑⚑ THE TALLY IS COMPUTED ONCE FROM THE ROWS, NEVER BY RE-WALKING. The origin spelled
`{k: sum(1 for _, st, _ in rows() if st == k) for k in (...)}` at three call sites, each re-running
every predicate — so a `cmd0` item shelled out once per tally. Worse than slow: a predicate reading
mutable state can answer differently between walks, and a table whose rows and whose footer
disagree is a report nobody can act on.

⚑ THE BLOCK MARKERS ARE THE CONTRACT WITH THE LEDGER, so they live beside the renderer that emits
them rather than in the caller. A writer that owns the markers and a reader that re-spells them is
the two-roster shape, and the markers are what makes the region replaceable at all.

⚑⚑ AND THE GATE REFUSED THE FIRST CUT FOR AN IMPLICIT CONCATENATION INSIDE THE BLOCK LIST
(`ISC004`), which is a correctness catch rather than a style one: two adjacent strings in a list
are one element until someone adds a comma, at which point they silently become two lines of
output. The footer is built as a named value first, so the list holds one expression per line it
emits.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, NamedTuple

from substrate import worklist_status

if TYPE_CHECKING:
    from collections.abc import Iterable, Sequence
    from pathlib import Path

#: The generated region's fences. A hand edit between them is overwritten by `--update`.
BEGIN = "<!-- worklist:auto BEGIN (regenerated by scripts/worklist.py --update; do not edit) -->"
END = "<!-- worklist:auto END -->"

#: The glyph for each verdict label — one place, so a table and its footer cannot disagree.
MARKS = {"DONE": "✅", "OPEN": "⬜", "MANUAL": "🔶"}

#: The verdict labels, in report order.
LABELS = ("DONE", "OPEN", "MANUAL")

#: Why the ledger's footer says the status cannot go stale — the tracker's whole claim.
_STALENESS_NOTE = (
    "Status is computed, not stored — a re-surfaced 'open' that is really done cannot occur."
)


class Row(NamedTuple):
    """One rendered worklist line: the symbol, its verdict label, and its description."""

    sym: str
    label: str
    desc: str


class Tally(NamedTuple):
    """How many items hold each verdict, computed ONCE from a materialised row list.

    ⚑ `total` IS DERIVED. A record carrying both the parts and their sum lets the two disagree,
    and this tally exists precisely because the origin recomputed it three times.
    """

    done: int
    open_: int
    manual: int

    @property
    def total(self) -> int:
        """Report how many items the tally covers."""
        return self.done + self.open_ + self.manual

    def why(self) -> str:
        """Return the one-line footer naming every component."""
        return f"{self.done} done · {self.open_} open · {self.manual} manual of {self.total}"


def rows(items: Sequence[dict[str, object]], *, root: Path, agda: Path) -> list[Row]:
    """Return one `Row` per item, evaluating each predicate EXACTLY ONCE.

    ⚑⚑ RETURNS A LIST, NOT A GENERATOR, AND THAT IS THE FIX RATHER THAN A STYLE CHOICE. The origin
    yielded, so every consumer that wanted both a table and a count walked it twice and ran every
    predicate twice — including `cmd0`, which shells out. A predicate that reads mutable state can
    answer differently across two walks, so the table and its own footer could disagree.
    """
    out: list[Row] = []
    for item in items:
        pred = item.get("done")
        verdict = (
            worklist_status.status(tuple(pred), root=root, agda=agda)
            if isinstance(pred, (list, tuple))
            else None
        )
        out.append(
            Row(
                str(item.get("sym", "?")), worklist_status.label(verdict), str(item.get("desc", ""))
            )
        )
    return out


def tally(rendered: Iterable[Row]) -> Tally:
    """Return the verdict counts over already-rendered rows."""
    counts = dict.fromkeys(LABELS, 0)
    for row in rendered:
        if row.label in counts:
            counts[row.label] += 1
    return Tally(counts["DONE"], counts["OPEN"], counts["MANUAL"])


def table(rendered: Iterable[Row]) -> list[str]:
    """Return the markdown table lines for `rendered`, header included."""
    lines = ["| status | sym | item |", "|---|---|---|"]
    lines.extend(
        f"| {MARKS.get(r.label, '?')} {r.label} | `{r.sym}` | {r.desc} |" for r in rendered
    )
    return lines


def block(rendered: Sequence[Row]) -> str:
    """Return the fenced ledger block for `rendered`, markers included.

    ⚑ THE FOOTER STATES WHY THE STATUS CANNOT GO STALE, in the artifact rather than in a comment
    nobody regenerating the block will read. The whole point of the tracker is that a finished arc
    cannot keep reading OPEN, and the reader of the ledger is who needs to know that.
    """
    counted = tally(rendered)
    footer = f"_{counted.why()}. {_STALENESS_NOTE}_"
    heading = "## Live status — DERIVED from the tree (run `scripts/worklist.py`; never hand-edit)"
    return "\n".join([BEGIN, heading, "", *table(rendered), "", footer, END])


def splice(text: str, rendered: Sequence[Row]) -> str:
    """Return `text` with the generated block replaced, or inserted after the intro.

    ⚑⚑ A MISSING MARKER PAIR INSERTS RATHER THAN RAISING, which is the origin's behaviour and is
    kept deliberately: the ledger is hand-authored prose that the block joins, so the first run
    against a fresh ledger must succeed. What is NOT kept is silent partial matching — both
    markers must be present to splice, because finding only one means the region's extent is
    unknown and overwriting from a guess is how a generated block eats prose.
    """
    fresh = block(rendered)
    if BEGIN in text and END in text:
        pre, rest = text.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        return pre + fresh + post
    split = text.find("\n\n")
    if split == -1:
        return fresh + "\n\n" + text
    return text[: split + 2] + fresh + "\n\n" + text[split + 2 :]
