"""Render a flat makefile for the Python selftests — one target per suite, membudget-gated.

⚑⚑⚑ THE POOL ALREADY EXISTS AND IT IS `make` (operator: *"a Flat.mk for the python self tests
wouldn't be out of place. Using the same membudget machinery that gates memory and concurrency
there."*). A hand-rolled runner would reimplement four things this composition gets free:

    jobserver          the launch cap — how many recipes are attempted at once
    membudget lease    the RUNNING-width authority — blocks until RAM fits
    membudget load     admission control at N x nproc, checked BEFORE the RAM probe
    membudget claim    exclusive access to a named artefact (`claim:<name>`)

⚑ INTERLEAVED OUTPUT IS FINE; A PRIORITY INVERSION IS NOT (operator). `--output-sync=target`
makes output readable at the cost of holding a target's stream until it completes — worth
having, not worth blocking on. What prevents inversion is the DAG plus the lease: a suite
waits for budget, not for an unrelated suite's output buffer.

⚑ THE STAMP IS THE ARTEFACT. A selftest produces no file, so each target touches a stamp under
`_build/selftest/`. That makes `make` incremental in the honest sense — a suite re-runs when
its SOURCE is newer than its stamp — and is why this is a DAG rather than a fan of phony
targets.

⚑⚑ THIS MODULE RENDERS; IT DECIDES NOTHING. The exclusion policy is `suite_claims`, discovery
is `suite_discovery`, the non-leaf set is `suite_declared`. A first cut held all four and
threading ONE parameter through it took six refused edits — the gate saying the unit was wrong
(operator: *"break it down"*).

⚑⚑⚑ AND HAVING NO ENTRYPOINT IS NOT THE SAME AS BEING UNRUNNABLE (Ⓝ72d
⟡bare-generator-empty-artifact). Until `_refuse` below, running this file directly executed the
module, defined its functions, accepted ANY flag, and exited 0 — rendering nothing and writing
nothing, with no output to say so. `selftest_mk`'s header records what that cost: a session ran
this file with `--check`, read exit 0, reported the roster current, and a newly-written suite
went unrun. The split that makes this a pure renderer is right; what was missing is that a pure
renderer must SAY SO when somebody tries to drive it.
"""

from __future__ import annotations

import sys
from pathlib import Path

from substrate import build_settings, corpus, suite_claims

# The membudget client — ONE authority, `build_settings.MEMBUDGET`, shared with the agda makefiles.
MEMBUDGET = str(build_settings.MEMBUDGET)

# Written at the head of the generated file so a reader knows not to hand-edit it.
MARKER = "# GENERATED by substrate/gen_selftest_mk.py — do not edit; run the generator."

# Where the stamps live. One per suite, mirroring the suite's own path.
BUILD = "_build/selftest"

# ⚑ THE LEASE IS `auto`, NOT A NUMBER, FOR THE REASON THE AGDA BUILD RECORDS: a hardcoded
# figure collapses every workload onto one number, over-sized for the median and under-sized
# for the tail AT THE SAME TIME. `auto` keys on the label and reads that suite's own recorded
# peaks, rounding up to the next power of two.
LEASE = "auto"


def stamp(label: str) -> str:
    """Return the stamp path for one suite's label."""
    return f"$(BUILD)/{label.replace('/', '__')}.ran"


def recipe(label: str, path: str, reaching: frozenset[str], fanout: frozenset[str]) -> list[str]:
    """Render the target for one suite."""
    rel = str(Path(path).relative_to(corpus.ROOT))
    tag = suite_claims.label_for(label, path, reaching, fanout)
    return [
        f"{stamp(label)}: {rel}",
        # ⚑ THE DIRECTORY IS MADE BEFORE THE WORK, NOT AFTER. A first draft emitted `mkdir`
        # after the suite, so a first run would touch a stamp into a directory that did not
        # exist — failing on a CLEAN TREE, precisely the run nobody has tried. Reading the
        # generated text caught it before running it did.
        "\t@mkdir -p $(dir $@)",
        # ⚑⚑ THE SUITE RUNS THROUGH `suite_run`, WHICH WRITES THE STAMP ITSELF (⟡last-retire).
        # `make` knows pass/fail; `suite_outcome` names seven kinds, and `vacuous` — reported
        # 0/0 — is decided WITHOUT consulting the exit code, so a suite can assert nothing and
        # still exit success. THE STAMP IS OURS TO DEFINE (operator: *"that stamp can hold
        # whatever you want it to, though? It can be JSON."*), so it carries the outcome rather
        # than being an empty marker with a second file beside it.
        #
        # ⚑ AND THERE IS NO `touch`: the stamp is written ONLY on `ok`, by the wrapper. A
        # `touch` here would stamp a failed run — marking the target satisfied so the next
        # build skips the suite, which is a failure that silences itself.
        f"\t@$(MEMBUDGET) run {LEASE} {tag} -- $(PY) -m substrate.suite_run {rel} $@ {label}",
        "",
    ]


def header(membudget: str, stamps: list[str]) -> list[str]:
    """Render the preamble and the `all` target."""
    return [
        MARKER,
        "#",
        "# ⚑ `make -jN` HERE IS SAFE BY CONSTRUCTION, NOT BY THE NUMBER. Every recipe routes",
        "# through `membudget run`, which blocks on a RAM lease AND on a load ceiling before",
        "# it starts anything — so -j is a launch cap and the lease decides real width. A",
        "# suite claiming an artefact waits for the holder rather than racing it.",
        "#",
        "# ⚑ RUN IT AS: make -f Selftest.mk -j20 --output-sync=target",
        "",
        f"MEMBUDGET := {membudget}",
        "PY := python3",
        f"BUILD := {BUILD}",
        "",
        ".PHONY: all clean list",
        "",
        "all: " + " ".join(stamps),
        "",
    ]


def footer(suites: list[tuple[str, str]]) -> list[str]:
    """Render the `list` and `clean` targets."""
    return [
        "list:",
        "\t@echo " + " ".join(f"'{label}'" for label, _p in suites) + " | tr ' ' '\\n'",
        "",
        # ⚑ CLEAN REMOVES STAMPS, NEVER SOURCE. A stamp is the only thing this build creates,
        # so `clean` is total and cannot reach anything a suite is made of.
        "clean:",
        "\t@rm -rf $(BUILD)",
        "",
    ]


def text(suites: list[tuple[str, str]], reaching: frozenset[str], fanout: frozenset[str]) -> str:
    """Render the whole makefile.

    ⚑⚑ AN EMPTY `suites` RENDERS A WELL-FORMED MAKEFILE WITH AN EMPTY ROSTER, and that is not a
    defect in THIS function — a renderer must render what it is given, and its cases hand it
    small fixture rosters on purpose. The defect is a CALLER that supplies no roster and cannot
    tell it supplied none. `_refuse` below is where that is stopped.
    """
    out = header(MEMBUDGET, [stamp(label) for label, _p in suites])
    for label, path in suites:
        out += recipe(label, path, reaching, fanout)
    return "\n".join(out + footer(suites))


def _refuse() -> int:
    """Refuse a direct invocation, naming the module that actually drives this one.

    ⚑⚑⚑ Ⓝ72d ⟡bare-generator-empty-artifact — A RENDERER WITH NO ENTRYPOINT ACCEPTS EVERY FLAG
    AND EXITS 0. MEASURED here before this guard existed: `gen_selftest_mk.py --check` printed
    nothing and returned 0, having rendered nothing and written nothing.

    ⚑⚑ THAT IS THE SAME SHAPE AS A RATCHET WHOSE BASELINE IS ABSENT EXITING 0 — the verdict came
    from a program that never looked, and nothing in the output could tell a reader which. The
    sibling `selftest_mk` records the exact incident: a session ran this file with `--check` to
    confirm the roster was current, read exit 0, reported the roster clean, and a suite went
    unrun. **A flag a program does not implement is indistinguishable from one it satisfies.**

    ⚑ REFUSING IS THE FIX, NOT DOCUMENTING IT. This repo's standing rule is that a policy living
    only in prose governs only the turns where it is already being thought about — and the prose
    warning was ALREADY WRITTEN, in the sibling's docstring, when the trap was hit. So the
    refusal is executable, it exits NON-ZERO, and it names the driver rather than describing the
    problem: the next reader gets the command they should have run.

    ⚑ AND IT DOES NOT GROW A `main` THAT WRITES. The split is deliberate and argued in
    `selftest_mk`'s header — the renderer takes data and returns text so a case need not touch a
    filesystem. A refusal is not a second responsibility; it is this module declining to have
    one.
    """
    sys.stderr.write(
        "gen_selftest_mk is a RENDERER and has no command line — it writes nothing and\n"
        "checks nothing. Invoked directly it would exit 0 having done nothing, which is\n"
        "indistinguishable from success (Ⓝ72d ⟡bare-generator-empty-artifact).\n"
        "\n"
        "The driver owns discovery, the roster and the file:\n"
        "    python3 -m substrate.selftest_mk            # write Selftest.mk\n"
        "    python3 -m substrate.selftest_mk --print    # render to stdout\n"
        "    python3 -m substrate.selftest_mk --check    # REFUSE if the committed file is "
        "stale\n"
    )
    return 2


# ⚑ `--selftest` DELEGATES TO THE SIBLING SUITE; EVERYTHING ELSE REFUSES. The suite arm must stay
# reachable — this module is a roster member, and a guard that refused unconditionally would make
# it report `refused` to the very runner whose makefile it renders.
if __name__ == "__main__":
    if "--selftest" in sys.argv:
        from substrate import gen_selftest_mk_selftest

        sys.exit(gen_selftest_mk_selftest.selftest())
    sys.exit(_refuse())
