"""The cases for `substrate.otlp_endpoint` — SDK precedence, the path suffix, the read split.

⚑⚑⚑ THE DOUBLED-SUFFIX ARM IS THE ONE THAT EARNS ITS KEEP, and it is a footgun on BOTH sides
of the wire. The OpenTelemetry spec makes the two env vars asymmetric: the GENERAL var is a
BASE the SDK appends `v1/metrics` to, while the SIGNAL var "MUST be used as-is". So a full
`.../opentelemetry/v1/metrics` value placed in the GENERAL var produces
`.../v1/metrics/v1/metrics` — a 404 that reads as a wrong host, sending a reader to debug
connectivity that is fine.

⚑ CASSIAN IS RECORDING THIS AGAINST THEIR RE-POINT MECHANISM (2026-08-31): their migration
dropins re-point by rewriting a full `host:port/path`, so handing that to a producer reading
the general var would double the suffix. Their corrected contract — set the SIGNAL var to a
full path, OR the general var to a base only — is exactly what these cases pin from our end.

⚑ AND THE READ/WRITE SPLIT IS NOT DERIVABLE. A206 moved the write onto vmagent (`:30828`,
serves no PromQL) while reads stayed on vm-read (`:30829`). Any code that computed one from
the other would encode a relationship that does not hold — so a case asserts they are
independently resolvable and independently defaulted.
"""

from __future__ import annotations

import os
import sys
from contextlib import contextmanager
from typing import TYPE_CHECKING

from substrate import otlp_endpoint

if TYPE_CHECKING:
    from collections.abc import Iterator

_SIGNAL = "https://collector.example/otlp/v1/metrics"
_BASE = "https://collector.example/otlp"


@contextmanager
def _env(**values: str | None) -> Iterator[None]:
    """Set env vars for the block and restore them after, whatever happens.

    ⚑ RESTORED IN A `finally`, because a case that leaves the environment mutated makes every
    later arm's result a fact about the arm that ran before it.
    """
    saved = {k: os.environ.get(k) for k in values}
    try:
        for k, v in values.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v
        yield
    finally:
        for k, v in saved.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v


def signal_var_used_as_is(out: list[str]) -> int:
    """Check the signal-specific var is used verbatim, path included.

    ⚑ THE SPEC SAYS "MUST be used as-is without any modification". Appending a path here would
    be the doubled suffix, generated by us instead of by the operator.
    """
    with _env(**{otlp_endpoint.WRITE_ENV: _SIGNAL, otlp_endpoint.WRITE_ENV_BASE: None}):
        got = otlp_endpoint.write_endpoint()
    if got != _SIGNAL:
        out.append(f"selftest: the signal var was modified: {got!r}")
        return 1
    return 0


def base_var_gets_the_path(out: list[str]) -> int:
    """Check the general var is treated as a BASE and gains `v1/metrics`."""
    bad = 0
    with _env(**{otlp_endpoint.WRITE_ENV: None, otlp_endpoint.WRITE_ENV_BASE: _BASE}):
        got = otlp_endpoint.write_endpoint()
    if got != f"{_BASE}/v1/metrics":
        out.append(f"selftest: the base var did not gain the metrics path: {got!r}")
        bad += 1
    with _env(**{otlp_endpoint.WRITE_ENV: None, otlp_endpoint.WRITE_ENV_BASE: _BASE + "/"}):
        got = otlp_endpoint.write_endpoint()
    if "//v1/metrics" in got:
        out.append(f"selftest: a trailing slash produced a doubled separator: {got!r}")
        bad += 1
    return bad


def signal_beats_base(out: list[str]) -> int:
    """Check signal-specific precedence, matching the SDK's own resolution order.

    ⚑ IMPLEMENTING HALF THE PRECEDENCE WOULD BE WORSE THAN NONE. An operator who sets both
    expects the specific one to win, as every OTel SDK does; disagreeing here would make our
    producer the one that behaves differently.
    """
    with _env(**{otlp_endpoint.WRITE_ENV: _SIGNAL, otlp_endpoint.WRITE_ENV_BASE: _BASE}):
        got = otlp_endpoint.write_endpoint()
    if got != _SIGNAL:
        out.append(f"selftest: the base var overrode the signal var: {got!r}")
        return 1
    return 0


def defaults_are_the_verified_ports(out: list[str]) -> int:
    """Check the unconfigured defaults are the ports verified 2026-08-31.

    ⚑ AND THAT THEY ARE DIFFERENT PORTS. `:30828` is vmagent (write relay, no PromQL) and
    `:30829` is vm-read. A default pointing both at one port is the exact defect this module
    replaced — a verify against the write port can never succeed, however long it waits, and
    reads as "the write failed".
    """
    bad = 0
    with _env(
        **{
            otlp_endpoint.WRITE_ENV: None,
            otlp_endpoint.WRITE_ENV_BASE: None,
            otlp_endpoint.READ_ENV: None,
        }
    ):
        write, read = otlp_endpoint.write_endpoint(), otlp_endpoint.query_base()
    if "30828" not in write:
        out.append(f"selftest: the write default is not the ingest port: {write!r}")
        bad += 1
    if "30829" not in read:
        out.append(f"selftest: the read default is not the query port: {read!r}")
        bad += 1
    if "8428" in write or "8428" in read:
        out.append("selftest: a default still names the retired port")
        bad += 1
    return bad


def read_is_independent(out: list[str]) -> int:
    """Check the read base is resolved on its own, not derived from the write URL."""
    bad = 0
    with _env(**{otlp_endpoint.WRITE_ENV: _SIGNAL, otlp_endpoint.READ_ENV: None}):
        if otlp_endpoint.query_base() != otlp_endpoint.DEFAULT_READ:
            out.append("selftest: setting the write endpoint moved the read base")
            bad += 1
    with _env(
        **{
            otlp_endpoint.WRITE_ENV: None,
            otlp_endpoint.WRITE_ENV_BASE: None,
            otlp_endpoint.READ_ENV: "http://reader.example",
        }
    ):
        if otlp_endpoint.write_endpoint() != otlp_endpoint.DEFAULT_WRITE:
            out.append("selftest: setting the read base moved the write endpoint")
            bad += 1
    return bad


def write_env_is_the_specified_name(out: list[str]) -> int:
    """Check the write knob is the OTel-specified name, not one we invented.

    ⚑ THE FIRST DRAFT INVENTED `SUBSTRATE_OTLP_METRICS`, which is not merely non-standard but
    REDUNDANT AND SHADOWING: `opentelemetry-python`'s `_resolve_endpoint` already reads these
    names, and our emitter uses that SDK. This arm fails if anyone renames it back.
    """
    bad = 0
    if not otlp_endpoint.WRITE_ENV.startswith("OTEL_EXPORTER_OTLP"):
        out.append(f"selftest: the write knob is not a specified name: {otlp_endpoint.WRITE_ENV!r}")
        bad += 1
    # ⚑ THE READ KNOB IS OURS BECAUSE NO STANDARD EXISTS — OTLP has no vocabulary for querying
    # your own emission. That is a different fact from "we preferred our own name".
    if otlp_endpoint.READ_ENV.startswith("OTEL_"):
        out.append("selftest: the read knob claims a standard name that does not exist")
        bad += 1
    return bad


_ARMS = (
    signal_var_used_as_is,
    base_var_gets_the_path,
    signal_beats_base,
    defaults_are_the_verified_ports,
    read_is_independent,
    write_env_is_the_specified_name,
)

_CASE_COUNT = 1 + 2 + 1 + 3 + 2 + 2


def selftest() -> int:
    """Run every arm and return an exit code."""
    out: list[str] = []
    failures = sum(arm(out) for arm in _ARMS)

    if failures:
        sys.stderr.write("\n".join(out) + "\n")
        sys.stderr.write(f"otlp-endpoint selftest: {failures} failure(s)\n")
        return 1
    sys.stdout.write(f"otlp-endpoint selftest: {_CASE_COUNT}/{_CASE_COUNT}\n")
    return 0


# ⚑ THE FLAG IS NAMED SO `run_selftests.discover()` SEES THIS SUITE (⟡selftest-discovery).
if __name__ == "__main__":
    sys.exit(selftest() if "--selftest" in sys.argv or len(sys.argv) == 1 else 0)
