"""The compiled-query cache: its text, its reader, and the drift verdict `--check` gates on.

⚑⚑⚑ THE THIRD CUT OF THE DRAIN'S SECOND FILE, AND THE ONE THAT IS A PRE-COMMIT GATE.
`query_defs.py --check` recompiles every builder in memory and diffs the result against the
committed `query_sql_postgres.py`, naming WHICH builders drifted. Two things happen there:
SQLAlchemy compiles each builder to `(sql, params)` — that loop stays in the origin, because
the builders live in `query_decl`, a bare-import module with SQLAlchemy under it — and
everything after the map exists: rendering the cache text, reading the committed one, and the
three-way verdict (missing / fresh / stale, with changed + added + removed by name). That is
this module, and it is pure over `{name: (sql, params)}`.

⚑⚑ THE COMMITTED CACHE IS THE DIFFERENTIAL. It was written by the origin's `compile_text`, so
re-rendering the map read back out of it must reproduce the file BYTE FOR BYTE — a case that
asserts this module's renderer against the origin's actual output without running SQLAlchemy.

⚑ NAME WHICH BUILDERS DRIFTED, NOT JUST THAT THE FILE DID (kept from the origin). A one-bit
STALE cannot discharge the obligation an optimisation carries — *this change touches the
licence and NOTHING ELSE*. Shared helpers feed several whole-tier readers, and the only
mechanical evidence they still compile identically is a per-name diff.

⚑ THE CACHE IS READ AS DATA, NEVER IMPORTED. The origin `import`s the committed module to
compare; importing a generated file to read a dict is a code path where a literal read
suffices, and `ast.literal_eval` narrows what comes back where an import yields `Any`.
"""

from __future__ import annotations

import ast
from dataclasses import dataclass
from typing import TYPE_CHECKING

from substrate import ruff_format

if TYPE_CHECKING:
    from pathlib import Path

# One compiled builder: its SQL text and its default parameters, keys sorted.
Entry = tuple[str, dict[str, object]]

# ⚑⚑⚑ THE LICENCE LINES ARE PART OF THE RENDERED TEXT, BY RULING. The origin's `compile_text`
# never emitted them, while the committed file carries them (the header gate's doing), so the
# origin's `--check` compared bytes that could never be equal and read STALE with "0 builder(s)
# differ" — a permanently red pre-commit gate that no `--compile` could turn green. Measured
# 2026-09-20; the operator had already ruled "compile_text should emit the SPDX header". Spelled
# exactly as the committed file spells it (no space after the colon), so the round trip holds.
LICENCE = "# SPDX-License-Identifier:Apache-2.0\n# Copyright 2026 Mike Mol\n"
HEADER = (
    LICENCE + "# GENERATED by query_defs.py --compile — DO NOT EDIT BY HAND.\n"
    "# Regenerate: python3 jea/metalanguage/query_defs.py --compile\n"
    "# The cached runtime (query_builders.py) executes SQL[name] with NO SQLAlchemy "
    "import.\n"
)

# The generated file's own path, which ruff is told so the project's config applies to it.
TARGET = "jea/metalanguage/query_sql_postgres.py"

# The arity of an entry tuple.
_PAIR = 2


def render(entries: dict[str, Entry]) -> str:
    """Render the cache module's source — deterministic, and `ruff format`-clean.

    ⚑ FORMATTED BY RUFF, NOT BY HAND (W39). The bulk format pass reformatted the committed file
    while this renderer still emitted one line per builder, so the byte round-trip `--check`
    rests on failed at the first entry. The raw rendering is unchanged (builders sorted, param
    keys sorted); ruff is then asked for its layout, so the two can only disagree if ruff does.
    """
    rows = [
        f"  {name!r}: ({entries[name][0]!r}, {entries[name][1]!r})," for name in sorted(entries)
    ]
    raw = HEADER + "SQL = {\n" + "\n".join(rows) + "\n}\n"
    return ruff_format.format_source(raw, TARGET)


def _narrow(value: object) -> dict[str, Entry]:
    """Narrow a literal-evaluated `SQL` dict to the entry shape, refusing anything else."""
    if not isinstance(value, dict):
        msg = "the cache's SQL is not a dict"
        raise TypeError(msg)
    out: dict[str, Entry] = {}
    for name, entry in value.items():
        if not (
            isinstance(name, str)
            and isinstance(entry, tuple)
            and len(entry) == _PAIR
            and isinstance(entry[0], str)
            and isinstance(entry[1], dict)
        ):
            msg = f"cache entry {name!r} is not (sql, params)"
            raise TypeError(msg)
        params: dict[str, object] = {str(k): v for k, v in entry[1].items()}
        out[name] = (entry[0], params)
    return out


def read(path: Path) -> dict[str, Entry] | None:
    """Return the committed cache's map, or None when the file is absent."""
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None
    tree = ast.parse(text, filename=str(path))
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id == "SQL"
        ):
            value: object = ast.literal_eval(node.value)
            return _narrow(value)
    msg = f"{path.name} declares no SQL dict"
    raise ValueError(msg)


@dataclass(frozen=True, slots=True)
class Drift:
    """Which builders differ between a fresh map and the committed one, by name."""

    changed: tuple[str, ...]
    added: tuple[str, ...]
    gone: tuple[str, ...]

    @property
    def stale(self) -> bool:
        """Report whether anything at all differs."""
        return bool(self.changed or self.added or self.gone)


def drift(fresh: dict[str, Entry], committed: dict[str, Entry]) -> Drift:
    """Compare the fresh map against the committed one, name for name."""
    changed = tuple(n for n in sorted(fresh) if n in committed and committed[n] != fresh[n])
    added = tuple(sorted(set(fresh) - set(committed)))
    gone = tuple(sorted(set(committed) - set(fresh)))
    return Drift(changed, added, gone)


def report(base: str, backend: str, count: int, found: Drift | None) -> tuple[list[str], bool]:
    """Render `--check`'s verdict lines in the origin's words; `None` means the file is missing."""
    remedy = f"SUBSTRATE_STORE={backend} python3 jea/metalanguage/query_defs.py --compile"
    if found is None:
        return [f"query_defs --check: {base} MISSING — run `{remedy}`"], False
    if not found.stale:
        return [f"query_defs --check: {base} fresh ({count} builders, {backend})"], True
    head = f"query_defs --check: {base} STALE — {len(found.changed)} builder(s) differ"
    if found.added:
        head += f", {len(found.added)} added"
    if found.gone:
        head += f", {len(found.gone)} removed"
    names = [*found.changed, *(f"+{n}" for n in found.added), *(f"-{n}" for n in found.gone)]
    return [head, *(f"    {n}" for n in names), f"  run `{remedy}`"], False
