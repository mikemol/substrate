# ── 1. numpy SEARCH ─────────────────────────────────────────────────────────
# (pure-tuple perm algebra; numpy used if present, but not required — the search
#  is over Sₙ which is finite and small.)

def compose(sigma, tau):
    """(compose σ τ)[i] = σ[τ[i]]  — the tower's `compose` semantics (lookup∘lookup)."""
    return tuple(sigma[tau[i]] for i in range(len(sigma)))

def closure_of(gens, n):
    """The subgroup generated by `gens` (+ identity) under compose. Returns (ordered
    element list with id first then the generators then the rest, index-map, product-table)."""
    ident = tuple(range(n))
    seen = {ident}
    frontier = [ident]
    while frontier:
        x = frontier.pop()
        for g in gens:
            for y in (compose(g, x), compose(x, g)):
                if y not in seen:
                    seen.add(y); frontier.append(y)
    # deterministic order: id, then the generators (in given order), then the rest sorted.
    ordered = [ident]
    for g in gens:
        if g not in ordered:
            ordered.append(g)
    for e in sorted(seen):
        if e not in ordered:
            ordered.append(e)
    idx = {e: i for i, e in enumerate(ordered)}
    table = {(i, j): idx[compose(ordered[i], ordered[j])]
             for i in range(len(ordered)) for j in range(len(ordered))}
    return ordered, idx, table

def cycle_type(p):
    n = len(p); seen = [False]*n; counts = [0]*(n+1)
    for i in range(n):
        if seen[i]:
            continue
        L = 0; j = i
        while not seen[j]:
            seen[j] = True; j = p[j]; L += 1
        counts[L] += 1
    return tuple(counts[1:])

