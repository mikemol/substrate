# split an Agda type on its top-level `→` (paren/brace/bracket depth 0) — the telescope domains + codomain.
def split_arrows(s):
    out = []
    d = 0
    cur = ""
    for ch in s:
        if ch in "([{":
            d += 1
        elif ch in ")]}":
            d -= 1
        if ch == "→" and d == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return out


