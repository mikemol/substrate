# ⚑ AND THE ASYMMETRY THAT LET IT THROUGH IS RECORDED IN THIS FILE'S OWN HEADER.
# `strip` was DELEGATED to `agda_lex.mask_comments`, which IS covered by four
# `test_agda_lex_*` modules; the hash STAYED LOCAL and was never tested. The header
# already records that this module once shipped a wrong `strip` to 19 importers
# including three gates — the same class, in the same file, caught by reading
# rather than by a test. This is the first test of the hash.
def _selftest():
    import tempfile

    cases = []

    def check(label, got, want):
        cases.append((label, got == want, got, want))

    d = tempfile.mkdtemp()

    def _w(nm, body):
        p = os.path.join(d, nm + ".agda")
        open(p, "w", encoding="utf-8").write(f"module Substrate.T.{nm} where\n" + body)
        return p

    # ⚑⚑ THE π-TYPE DEFECT. A declaration is a family of constructors, each a
    # Π-type into the carrier; the shape is that MULTISET of domains. `S K I : T`
    # is TELESCOPE SUGAR for three Π-types, and hashing the LINE recorded one
    # domain where there are three. MEASURED as a FOUR-WAY collision on
    # `⟦533ef80d⟧` spanning arities 2 and 4: `{S K I, _∙_}`, `{S K I, app}`,
    # `{M B I, _·_}` (four constructors each) and `{atom, app}` (two).
    _w("Three", "data T : Set where\n  S K I : T\n  _∙_ : T → T → T\n")
    _w("One", "data T : Set where\n  atom : T\n  app : T → T → T\n")
    ds = shape_decls(d)
    hs = {m: sh for m, _k, _dc, sh in ds["T"]}
    three = next(v for k, v in hs.items() if k.endswith("Three"))
    one = next(v for k, v in hs.items() if k.endswith("One"))
    check("⚑⚑ a 3-constant carrier and a 1-constant carrier hash DIFFERENTLY", three != one, True)
    # ⚑ AND THE HARM WAS NOT ONLY A MISLED READER: `genuine_ambiguity` keys on the
    # HASH, so a false collision SUPPRESSES a real ambiguity — the false-zero
    # inside the gate built to prevent it.
    check("⚑ so the two ARE reported as a genuine ambiguity", "T" in genuine_ambiguity(ds), True)
    # ⚑ SAME SHAPE STILL AGREES — the fix must not make every declaration unique,
    # which would be a different way of reporting nothing.
    _w("SameA", "data U : Set where\n  a b : U\n  f : U → U → U\n")
    _w("SameB", "data U : Set where\n  x y : U\n  g : U → U → U\n")
    ds2 = shape_decls(d)
    hu = {sh for m, _k, _dc, sh in ds2["U"]}
    check("⚑ two carriers of the SAME π-shape still share one hash", len(hu), 1)
    check("...and are therefore NOT a genuine ambiguity", "U" in genuine_ambiguity(ds2), False)
    # ⚑ `desc` WAS ALWAYS RIGHT — it renders from `heads`, which is why the index
    # printed `{S K I, _∙_}` beside a hash that disagreed with it. Pin that the two
    # halves now agree, since computing them from one parse is the actual fix.
    dsc = next(dc for m, _k, dc, _s in ds["T"] if m.endswith("Three"))
    check(
        "⚑ desc and hash now come from ONE parse (heads carry every name)",
        dsc,
        "data {S, K, I, _∙_}",
    )

    ok = sum(1 for _n, g, _a, _b in cases if g)
    for n_, g, got_, want in cases:
        if not g:
            print(f"  FAIL {n_}\n       got {got_!r} want {want!r}")
    print(f"_agdatext selftest: {ok}/{len(cases)}")
    return ok == len(cases)


if __name__ == "__main__":
    sys.exit(0 if _selftest() else 1)
