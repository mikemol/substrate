# drop Agda comments. DELEGATES to scratch/agda_lex.mask_comments — the one authority.
#
# ⚑ THIS LIFT LANDED ON THE WRONG REPRESENTATIVE.  The codemod that created this module
# required "VERBATIM family representatives", so it consolidated 15 copies onto whichever
# body it matched — and that body was the WEAKER stripper:
#
#   * `\{-.*?-\}` is NON-GREEDY, so it stops at the FIRST `-}`.  Agda block comments
#     NEST: `{- x {- y -} z -}` leaves `z -}` as live text, and every consumer then
#     censuses commented-out code as real.
#   * `--[^\n]*` fires anywhere, but Agda's lexer reads `-->` as a NAME, so an operator
#     containing `--` was silently eaten.
#
# 19 importers inherited both bugs, three of them PRE-COMMIT GATES (check_carrier_locality,
# and via it check_sumtype_ratchet and check_public_ratchet).  `agda_lex.mask_comments` is
# nesting-aware, treats `-->` as a name, and preserves LENGTH and line structure — so it is
# a strict drop-in here (this function's callers only ever re-scan the result).
#
# The signature and name are unchanged: fixing the canonical fixes every consumer at once,
# which is the entire point of having one.
def strip(s):
    return _mask(s)


# ─────────────────────────────────────────────────────────────────────────────
# THE SHAPE AUTHORITY — one computation of "does this name point at >1 node".
#
# ⚑⚑⚑ TWO GATES COMPUTED THIS RELATION SEPARATELY AND DISAGREED, AND THE
# DISAGREEMENT REACHED AN OPERATOR AS AN UNUSABLE REMEDY.  `check_import_shape.py`
# FAILS on a bare colliding import and tells the reader to specialize by shape
# "(see scratch/sppf_collision_index.md)" — an index generated by
# `sppf_node_index.py`.  Both walked `agda/Substrate` themselves, both matched
# `^(data|record)\s+(\S+)`, both hashed `sha1(kind|sorted-bodies)[:8]`.  The hash
# is BYTE-IDENTICAL between them; what diverged is everything around it:
#
#   * `ALLOW = {⊤,⊥,⊤₁}` existed ONLY in the gate (level-poly foundation dups —
#     same object, lifted, so the level IS the spec).  The index has no ALLOW, so
#     it publishes `⊤`/`⊥` as genuinely ambiguous where the gate exempts them.
#   * The index requires >1 distinct MODULE before testing shapes; the gate tests
#     shapes across all declarations.  Different populations, same predicate.
#
# ⚑ THE PRECEDENT IS IN THE GATE ITSELF, ONE FUNCTION OVER.  `check_import_shape`
# already records adopting `scope_fix._rename_pairs` — *"THE renaming-clause
# parser; never re-derive… this is the fourth adopter"* — after its private copy
# was found blind to 52 statements.  **The parser got unified; the ambiguity
# computation did not.**  Same file, same lesson, unlearned for the neighbouring
# relation.
#
# ⚑ AND THE FIX IS SUBTRACTIVE.  Making two independent computations AGREE keeps
# both and adds a reconciliation — a third thing to drift.  One computes; the
# other reads.
def shape_decls(root, with_path=False):
    """{name: [(module, kind, descriptor, shape_hash)]} — every `data`/`record`.

    `with_path=True` appends the file PATH and the constructor/field HEADS, giving
    `(module, kind, descriptor, shape_hash, path, heads)`.

    ⚑ THE PATH IS AN EXTRA COLUMN, NOT A SECOND MODE.  `decl_shape_tag` appends a
    tag to a LINE IN A FILE, so it needs the path; `sppf_node_index` publishes by
    module name.  Serving both from one walk is what removes the last private copy
    of the hash — the alternative was for the tagger to re-walk and re-hash, which
    is how there came to be three copies in the first place.

    ⚑ NO `allow` PARAMETER HERE, DELIBERATELY.  The exemption is a property of the
    VERDICT, not of the census: the index must still SHOW `⊤`/`⊥` and their shapes,
    while the gate must not FAIL on them.  Taking `allow` here would have made the
    two callers pass different arguments to one function and diverge again — the
    same split under a shared name, which is worse than two honest copies.
    """
    import collections
    import hashlib

    sys.path.insert(
        0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scratch")
    )
    from agda_lex import HEADER as _HEADER  # THE header authority; never re-derive

    decls = collections.defaultdict(list)
    declre = re.compile(r"^(data|record)\s+(\S+)(.*)$")
    for dp, _, fns in os.walk(root):
        for fn in fns:
            if not fn.endswith(".agda"):
                continue
            p = os.path.join(dp, fn)
            t = strip(open(p, encoding="utf-8").read())
            mm = _HEADER.search(t)
            mod = mm.group(1) if mm else os.path.relpath(p, root)
            lines = t.splitlines()
            i = 0
            while i < len(lines):
                m = declre.match(lines[i])
                if not m:
                    i += 1
                    continue
                kind, name, rest = m.group(1), m.group(2), m.group(3)
                heads, body, j = [], [rest], i + 1
                while j < len(lines) and (lines[j].strip() == "" or lines[j][:1] in " \t"):
                    s = lines[j].strip()
                    if " : " in s:
                        # ⚑⚑ ONE ENTRY PER *NAME*, NOT PER LINE — THE Π-TYPE, NOT THE
                        # SURFACE SYNTAX. A declaration is a family of constructors,
                        # each a Π-type into the carrier, and the shape is that
                        # MULTISET of domains. `S K I : Tm` is TELESCOPE SUGAR for
                        # three Π-types; hashing the line recorded ONE domain where
                        # there are THREE, so the hash was not computing the π-type at
                        # all — it was computing the multiset of right-hand-sides of
                        # colons, which coincides with the π-type only when nobody
                        # uses the sugar.
                        #
                        # ⚑ MEASURED — A FOUR-WAY COLLISION SPANNING TWO ARITIES.
                        # `⟦533ef80d⟧` was carried by `SKIShedDuality {S K I, _∙_}`,
                        # `AgdaExtrude {S K I, app}`, `FUSepConvEtaWitness {M B I, _·_}`
                        # (all FOUR constructors) and `FUSepQReduce {atom, app}` (TWO).
                        # A free tree over three points and a free tree over one point
                        # hashed identically.
                        #
                        # ⚑⚑ AND THE HARM IS NOT ONLY A MISLED READER. `genuine_ambiguity`
                        # keys its verdict on the hash (`row[3]`), so a FALSE collision
                        # SUPPRESSES a real ambiguity finding in `check_import_shape` and
                        # in the published index — the false-zero-gets-banked shape,
                        # inside the gate built to prevent it. Two sessions acted on the
                        # false signal before it was caught by reading the declarations.
                        #
                        # ⚑ `desc` WAS ALWAYS RIGHT, which is why this hid: it renders
                        # from `heads`, so the index printed `{S K I, _∙_}` beside a hash
                        # that disagreed with it. The rendering and the verdict were
                        # computed from different halves of the same parse.
                        lhs, rhs = s.split(" : ", 1)
                        for nm in lhs.split() or [lhs.strip()]:
                            heads.append(nm)
                            body.append(rhs)
                    j += 1
                desc = (
                    f"{kind} {{{', '.join(heads[:5])}{'…' if len(heads) > 5 else ''}}}"
                    if heads
                    else kind
                )
                sh = hashlib.sha1(
                    (kind + "|" + "|".join(sorted(" ".join(b.split()) for b in body))).encode()
                ).hexdigest()[:8]
                decls[name].append(
                    (mod, kind, desc, sh)
                    if not with_path
                    else (mod, kind, desc, sh, p, ",".join(h for h in heads[:3] if h))
                )
                i = j
    return decls


def genuine_ambiguity(decls, allow=()):
    """{name} declared in >1 MODULE with >1 distinct shape — minus `allow`.

    ⚑ THE MODULE TEST IS PART OF THE PREDICATE, not an index-only nicety.  A name
    declared twice in ONE module with two shapes is not an import-time ambiguity:
    no consumer can bring in both, so there is nothing to specialize.  The gate
    omitted this and so tested a wider population than the index published — one
    half of why they disagreed.
    """
    # ⚑ INDEXED, NOT UNPACKED, so the predicate is identical under `with_path`.
    # `{m for m,_,_,_ in v}` binds the arity into the verdict: it raises on the
    # 6-tuple form, so the tagger and the index would have needed two spellings of
    # one predicate — the split this consolidation exists to remove, re-created in
    # the consolidated function.
    out = set()
    for n, v in decls.items():
        if len({row[0] for row in v}) <= 1:
            continue
        if len({row[3] for row in v}) > 1:
            out.add(n)
    return out - set(allow)


